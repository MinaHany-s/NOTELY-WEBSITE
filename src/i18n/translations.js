export function translateText(text, language = "en", values = {}) {
  if (typeof text !== "string") return text;
  const translated = language === "ar" ? (arabic[text] || text) : text;
  return translated.replace(/\{(\w+)\}/g, (_, key) => {
    const value = values[key];
    if (value === undefined || value === null) return `{${key}}`;
    if (language === "ar" && typeof value === "number") {
      return new Intl.NumberFormat("ar-EG").format(value);
    }
    return String(value);
  });
}

export function translateCurrent(text, values = {}) {
  const language = document.documentElement.lang === "ar" ? "ar" : "en";
  return translateText(text, language, values);
}
